def make(groups,prefix):
    rows=[]
    for category,(label,block) in groups.items():
        for i,line in enumerate(block.strip().splitlines()):
            parts=line.split('\t')
            assert len(parts)<=2
            history=[turn('You',parts[1])] if len(parts)==2 else []
            c=case(f'{prefix}-{category}-{i}',f'{prefix}-{category}-{i}',parts[0],label,history)
            c['category']=category
            c['annotation_reason']=('The latest speaker invites an explanation or continuation now; a clear main request survives incomplete grammar.' if label else 'The utterance reports/narrates, explicitly withholds an invitation, or has not yet supplied an identifiable requested task.')
            rows.append(c)
    return rows


def main():
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);a=p.parse_args()
    if a.out.exists():raise SystemExit('Refusing to overwrite unscored holdouts')
    development=make(DEV,'implicit-dev');fresh=make(FINAL,'implicit-final')
    assert len(development)==128 and sum(c['respond'] for c in development)==64
    assert len(fresh)==160 and sum(c['respond'] for c in fresh)==81
    # Fixed balanced stress subset for model selection; all final cases are
    # independently paired with saturated history by the acceptance evaluator.
    for label in [True,False]:
        for c in [r for r in development if r['respond']==label][::4][:16]:
            c=copy.deepcopy(c);c['id']+='-long'
            history=[turn('Them' if i%2 else 'You',('此前的请求已经回答完毕。请复述上次的校验依据。' if i%2 else '上次的依据已写入记录，讨论已经完成。')*16,bool(i%2)) for i in range(40)]
            c['context']['recentTurns']=history+c['context']['recentTurns'];development.append(c)
    a.out.mkdir(parents=True)
    hashes={}
    for name,rows in [('development',development),('acceptance',fresh)]:
        dest=a.out/(name+'.json');dest.write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
        hashes[name]=hashlib.sha256(dest.read_bytes()).hexdigest()
    audit=dict(created_at_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),scores_seen=False,annotation_policy='Response needed now; clear intent suffices without grammatical completeness. Ambiguous bare fragments avoided before scoring.',single_annotator=True,sha256=hashes)
    (a.out/'pre-score-review.json').write_text(json.dumps(audit,indent=2)+'\n')
    print(json.dumps(dict(development=len(development),acceptance=len(fresh),sha256=hashes),indent=2))


if __name__=='__main__':main()
